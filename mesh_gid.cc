// control_mesh_gid_batch (manual Professional 6.200) and the mesh_gid_*
// geometry records (6.818-6.853).
//
// control_mesh_gid_batch index -yes writes the mesh_gid_* records as the
// GiD batch file GidMeshBatch.bch, in the format of the Professional
// 02-08-2026 (byte equal on its test/other/mesh_gid_1..8 examples). When
// gid is on the PATH it runs "gid -n -b GidMeshBatch.bch" (the tochnog.gid
// problem type writes mesh_gid.gid/mesh_gid.dat), copies that file to
// <index>.dat and removes the batch file and the mesh_gid.gid directory, so
// that control_input of the same index reads the mesh. Without gid the
// batch file is kept, a warning is printed and the run continues.
//
// GiD numbering. Every object adds points, lines, surfaces and volumes to
// the GiD model; the batch file refers to them by running counters:
//   point            1 point
//   line             1 line
//   circle (filled)  1 point, 1 line, 1 surface
//   circle (hollow)  2 points, 2 lines (two arcs)
//   arc              3 points, 1 line
//   rectangle        4 points, 4 lines, 1 surface (deleted when hollow)
//   cylinder         4 points, 6 lines, 4 surfaces, 1 volume (deleted when
//                    hollow)
//   sphere           2 points, 4 lines, 4 surfaces, 1 volume (idem)
// Point numbers in mesh_gid_line_point, line numbers in mesh_gid_surface_line
// and surface numbers in mesh_gid_volume_surface are written as given: they
// are GiD numbers, which echo -yes prints for every object.

#include "tochnog.h"
#include <sys/stat.h>
#include <sys/types.h>
#include <dirent.h>
#include <unistd.h>

#define MESH_GID_BATCH_FILE "GidMeshBatch.bch"
#define MESH_GID_PROJECT_DIR "mesh_gid.gid"
#define MESH_GID_RESULT_FILE "mesh_gid.gid/mesh_gid.dat"

  // geometry_list ranges of the mesh_gid_assign_conditions_* records
#define MESH_GID_CONDITIONS_N 10

static std::string mesh_gid_g( double value )

{
  char str[MCHAR];

  snprintf( str, MCHAR, "%g", value );
  return std::string( str );
}

static long int mesh_gid_ints( long int idat, long int index, long int ival[] )

{
  long int length=0;
  double ddum[1];

  db( idat, index, ival, ddum, length, VERSION_NORMAL, GET_IF_EXISTS );
  return length;
}

static long int mesh_gid_dbls( long int idat, long int index, double dval[] )

{
  long int length=0, idum[1];

  db( idat, index, idum, dval, length, VERSION_NORMAL, GET_IF_EXISTS );
  return length;
}

static long int mesh_gid_switch( long int idat, long int index )

{
  long int ival[1];

  ival[0] = -NO;
  if ( !mesh_gid_ints( idat, index, ival ) ) return 0;
  return ival[0]==-YES;
}

static long int mesh_gid_max( long int idat )

{
  long int max=-1;

  db_highest_index( idat, max, VERSION_NORMAL );
  return max;
}

  // the echo -yes report of the GiD numbers an object generates
static void mesh_gid_report( const char *label, long int first, long int n )

{
  long int i=0;

  if ( !echo || n<=0 ) return;
  cout << "   " << label << " numbers: ";
  for ( i=0; i<n; i++ ) cout << first+i << " ";
  cout << "\n";
}

static void mesh_gid_report_object( const char *type, long int index,
  long int point, long int npoint, long int line, long int nline,
  long int surface, long int nsurface, long int volume, long int nvolume )

{
  if ( !echo ) return;
  cout << "generated by MESH_GID_" << type << " index: " << index << "\n";
  mesh_gid_report( "point", point, npoint );
  mesh_gid_report( "line", line, nline );
  mesh_gid_report( "surface", surface, nsurface );
  mesh_gid_report( "volume", volume, nvolume );
}

static void mesh_gid_dimension_error( void )

{
  pri( "\n\n Error: inconsistent with number_of_space_dimensions." );
  exit(TN_EXIT_STATUS);
}

  // input checks, made before the batch file is written
static void mesh_gid_check( void )

{
  long int index=0, max=-1, n=0, nlin=0, base=0, ifam=0, length=0,
    idat_conditions[3] = { MESH_GID_ASSIGN_CONDITIONS_POINT,
    MESH_GID_ASSIGN_CONDITIONS_LINE, MESH_GID_ASSIGN_CONDITIONS_SURFACE },
    *ival=NULL;
  double dval[DATA_ITEM_SIZE];

  if ( !db_active_index( MESH_GID_SIZE, 0, VERSION_NORMAL ) )
    db_error( MESH_GID_SIZE, -1 );

  if ( ndim==3 ) {
    if ( mesh_gid_max( MESH_GID_ARC_COORD )>=0 )
      db_error( MESH_GID_ARC_COORD, mesh_gid_max( MESH_GID_ARC_COORD ) );
  }
  else {
    if ( mesh_gid_max( MESH_GID_CYLINDER_COORD )>=0 ||
         mesh_gid_max( MESH_GID_SPHERE_COORD )>=0 ||
         mesh_gid_max( MESH_GID_VOLUME_SURFACE )>=0 )
      mesh_gid_dimension_error();
  }

    // an object needs all its size records
  if ( ndim==2 ) {
    max = mesh_gid_max( MESH_GID_CIRCLE_COORD );
    for ( index=0; index<=max; index++ ) {
      if ( !db_active_index( MESH_GID_CIRCLE_COORD, index, VERSION_NORMAL ) ) continue;
      if ( !db_active_index( MESH_GID_CIRCLE_RADIUS, index, VERSION_NORMAL ) )
        db_error( MESH_GID_CIRCLE_RADIUS, index );
    }
  }
  max = mesh_gid_max( MESH_GID_CYLINDER_COORD );
  for ( index=0; index<=max; index++ ) {
    if ( !db_active_index( MESH_GID_CYLINDER_COORD, index, VERSION_NORMAL ) ) continue;
    if ( !db_active_index( MESH_GID_CYLINDER_NORMAL, index, VERSION_NORMAL ) )
      db_error( MESH_GID_CYLINDER_NORMAL, index );
    if ( !db_active_index( MESH_GID_CYLINDER_RADIUS, index, VERSION_NORMAL ) )
      db_error( MESH_GID_CYLINDER_RADIUS, index );
    if ( !db_active_index( MESH_GID_CYLINDER_HEIGHT, index, VERSION_NORMAL ) )
      db_error( MESH_GID_CYLINDER_HEIGHT, index );
  }
  max = mesh_gid_max( MESH_GID_SPHERE_COORD );
  for ( index=0; index<=max; index++ ) {
    if ( !db_active_index( MESH_GID_SPHERE_COORD, index, VERSION_NORMAL ) ) continue;
    if ( !db_active_index( MESH_GID_SPHERE_RADIUS, index, VERSION_NORMAL ) )
      db_error( MESH_GID_SPHERE_RADIUS, index );
  }

    // concentration weights between -1 and +1 (manual 6.832)
  max = mesh_gid_max( MESH_GID_LINE_STRUCTURED_CONCENTRATE );
  for ( index=0; index<=max; index++ ) {
    if ( mesh_gid_dbls( MESH_GID_LINE_STRUCTURED_CONCENTRATE, index, dval )==0 )
      continue;
    if ( dval[0]<-1. || dval[0]>1. || dval[1]<-1. || dval[1]>1. ) {
      pri( "\nError: the weights of mesh_gid_line_structured_concentrate need to "
        "be between -1 and +1." );
      db_error( MESH_GID_LINE_STRUCTURED_CONCENTRATE, index );
    }
  }

    // one number of elements for each line of a structured surface (6.850)
  ival = get_new_int( DATA_ITEM_SIZE );
  max = mesh_gid_max( MESH_GID_SURFACE_STRUCTURED_NEL );
  for ( index=0; index<=max; index++ ) {
    n = mesh_gid_ints( MESH_GID_SURFACE_STRUCTURED_NEL, index, ival );
    if ( n==0 ) continue;
    nlin = mesh_gid_ints( MESH_GID_SURFACE_LINE, index, ival );
    if ( nlin>0 && n!=nlin ) {
      pri( "\nError: mesh_gid_surface_structured_nel needs one number for each "
        "line of mesh_gid_surface_line." );
      db_error( MESH_GID_SURFACE_STRUCTURED_NEL, index );
    }
  }

    // geometry_list indices 1..10 (points), 11..20 (lines) and 21..30
    // (surfaces), starting at the first one without gaps (6.818-6.820)
  for ( ifam=0; ifam<3; ifam++ ) {
    base = 1 + ifam*MESH_GID_CONDITIONS_N;
    max = mesh_gid_max( idat_conditions[ifam] );
    for ( index=0; index<=max; index++ ) {
      length = mesh_gid_ints( idat_conditions[ifam], index, ival );
      if ( length>0 && ( index<base || index>=base+MESH_GID_CONDITIONS_N ) ) {
        cout << "\nError: the index of " << db_name( idat_conditions[ifam] )
          << " needs to be " << base << " up to "
          << base+MESH_GID_CONDITIONS_N-1 << ".\n";
        db_error( idat_conditions[ifam], index );
      }
    }
    for ( index=base; index<=max; index++ ) {
      if ( !db_active_index( idat_conditions[ifam], index, VERSION_NORMAL ) ) {
        cout << "\nError: the indices of " << db_name( idat_conditions[ifam] )
          << " need to start at " << base << " without gaps; index " << index
          << " is missing.\n";
        db_error( idat_conditions[ifam], index );
      }
    }
  }
  delete[] ival;
}

  // element type of a mesh_gid_surface_element record (6.847); default
  // linear: triangles in 2D, tetrahedrons in 3D
static void mesh_gid_surface_element( FILE *fp, long int index, long int surface )

{
  long int element[1], triangle=0, quadrilateral=0, quadratic=0;

  element[0] = ( ndim==2 ) ? -TRIA3 : -TET4;
  mesh_gid_ints( MESH_GID_SURFACE_ELEMENT, index, element );
  triangle = element[0]==-TRIA3 || element[0]==-TRIA6;
  quadrilateral = element[0]==-QUAD4 || element[0]==-QUAD8 ||
    element[0]==-QUAD9 || element[0]==-HEX8 || element[0]==-HEX20 ||
    element[0]==-HEX27;
  if      ( element[0]==-TRIA6 || element[0]==-QUAD8 || element[0]==-TET10 ||
            element[0]==-HEX20 )
    quadratic = 1;
  else if ( element[0]==-QUAD9 || element[0]==-HEX27 )
    quadratic = 2;
  if ( triangle )
    fprintf( fp, "Mescape Meshing ElemType Triangle\n%ld\nescape\n", surface );
  else if ( quadrilateral )
    fprintf( fp, "Mescape Meshing ElemType Quadrilateral\n%ld\nescape\n", surface );
  if ( quadratic )
    fprintf( fp, "Mescape Utilities Variables Model(QuadraticType) %ld\n%ld\nescape\n",
      quadratic, surface );
}

static void mesh_gid_write( FILE *fp )

{
  long int index=0, max=0, i=0, n=0, nel[1], group[1], ipoint=0, iline=0,
    isurface=0, ivolume=0, base=0, ifam=0, *ival=NULL, *nval=NULL,
    idat_conditions[3] = { MESH_GID_ASSIGN_CONDITIONS_POINT,
    MESH_GID_ASSIGN_CONDITIONS_LINE, MESH_GID_ASSIGN_CONDITIONS_SURFACE };
  double dval[DATA_ITEM_SIZE], size[1], x=0., y=0., r=0.;
  const char *conditions_name[3] = { "points", "lines", "surfaces" },
    *conditions_type[3] = { "POINT", "LINE", "SURFACES" },
    *conditions_label[3] = { "point", "line", "surface" };

  ival = get_new_int( DATA_ITEM_SIZE );
  nval = get_new_int( DATA_ITEM_SIZE );

  fprintf( fp, "Mescape Files SaveAs -geoversion:current -- mesh_gid.gid\n" );
  fprintf( fp, "Mescape Data Defaults ProblemType yes tochnog\n" );

    // points
  max = mesh_gid_max( MESH_GID_POINT_COORD );
  if ( max>=0 ) fprintf( fp, "Mescape Utilities Variables CreateAlwaysNewPoint 1\n" );
  for ( index=0; index<=max; index++ ) {
    if ( !mesh_gid_dbls( MESH_GID_POINT_COORD, index, dval ) ) continue;
    fprintf( fp, "Mescape Geometry Create Point\n" );
    if ( ndim==2 )
      fprintf( fp, "%s %s 0.0 \n", mesh_gid_g(dval[0]).c_str(),
        mesh_gid_g(dval[1]).c_str() );
    else
      fprintf( fp, "%s %s %s \n", mesh_gid_g(dval[0]).c_str(),
        mesh_gid_g(dval[1]).c_str(), mesh_gid_g(dval[2]).c_str() );
    fprintf( fp, "escape\nescape\nescape\n" );
    ipoint++;
    mesh_gid_report_object( "POINT", index, ipoint, 1, 0, 0, 0, 0, 0, 0 );
  }

    // lines
  max = mesh_gid_max( MESH_GID_LINE_POINT );
  if ( max>=0 ) fprintf( fp, "Mescape Utilities Variables CreateAlwaysNewPoint -2\n" );
  for ( index=0; index<=max; index++ ) {
    if ( !mesh_gid_ints( MESH_GID_LINE_POINT, index, ival ) ) continue;
    iline++;
    fprintf( fp, "Mescape Geometry Create Line\n%ld\n%ld\nescape\nescape\nescape\n",
      ival[0], ival[1] );
    if ( mesh_gid_ints( MESH_GID_LINE_ELEMENT_GROUP, index, group ) )
      fprintf( fp, "Mescape Data Mat Assign GROUP_%ld Lines\n%ld\n"
        "escape\nescape\nescape\n", group[0], iline );
    if ( mesh_gid_dbls( MESH_GID_LINE_SIZE, index, size ) )
      fprintf( fp, "Mescape Meshing Structured Lines Size\n%s\n%ld\n"
        "escape\nescape\nescape\n", mesh_gid_g(size[0]).c_str(), iline );
    if ( mesh_gid_ints( MESH_GID_LINE_STRUCTURED_NEL, index, nel ) )
      fprintf( fp, "Mescape Meshing Structured Lines\n%ld\n%ld\n"
        "escape\nescape\nescape\n", nel[0], iline );
    if ( mesh_gid_dbls( MESH_GID_LINE_STRUCTURED_SIZE, index, size ) )
      fprintf( fp, "Mescape Meshing Structured Lines Size\n%s\n%ld\n"
        "escape\nescape\nescape\n", mesh_gid_g(size[0]).c_str(), iline );
    if ( mesh_gid_dbls( MESH_GID_LINE_STRUCTURED_CONCENTRATE, index, dval ) )
      fprintf( fp, "Mescape Meshing StructConcentr\n%ld\nescape\n%s %s\nescape\n",
        iline, mesh_gid_g(dval[0]).c_str(), mesh_gid_g(dval[1]).c_str() );
    mesh_gid_report_object( "LINE", index, 0, 0, iline, 1, 0, 0, 0, 0 );
  }

    // circles (2D only; the Professional writes nothing usable for them
    // in 3D)
  max = ( ndim==2 ) ? mesh_gid_max( MESH_GID_CIRCLE_COORD ) : -1;
  if ( max>=0 ) fprintf( fp, "Mescape Utilities Variables CreateAlwaysNewPoint 1\n" );
  for ( index=0; index<=max; index++ ) {
    if ( !mesh_gid_dbls( MESH_GID_CIRCLE_COORD, index, dval ) ) continue;
    x = dval[0]; y = dval[1];
    mesh_gid_dbls( MESH_GID_CIRCLE_RADIUS, index, dval );
    r = dval[0];
    if ( mesh_gid_switch( MESH_GID_CIRCLE_HOLLOW, index ) ) {
        // two arcs, upper and lower half
      for ( i=0; i<2; i++ ) {
        fprintf( fp, "Mescape Geometry Create Arc\n" );
        fprintf( fp, "%s %s 0.0\n", mesh_gid_g(x-r).c_str(), mesh_gid_g(y).c_str() );
        fprintf( fp, "%s %s 0.0\n", mesh_gid_g(x).c_str(),
          mesh_gid_g( i==0 ? y+r : y-r ).c_str() );
        fprintf( fp, "%s %s 0.0\n", mesh_gid_g(x+r).c_str(), mesh_gid_g(y).c_str() );
        fprintf( fp, "escape\n" );
      }
      mesh_gid_report_object( "CIRCLE", index, ipoint+1, 2, iline+1, 2, 0, 0, 0, 0 );
      ipoint += 2; iline += 2;
    }
    else {
      fprintf( fp, "Mescape Geometry Create Object CirclePNR %s %s 0 0 0 1 \n%s\n",
        mesh_gid_g(x).c_str(), mesh_gid_g(y).c_str(), mesh_gid_g(r).c_str() );
      isurface++;
      if ( mesh_gid_ints( MESH_GID_CIRCLE_ELEMENT_GROUP, index, group ) )
        fprintf( fp, "Mescape Data Mat Assign GROUP_%ld Surfaces\n%ld \nescape\n",
          group[0], isurface );
        // the Professional reports no surface number for a circle
      mesh_gid_report_object( "CIRCLE", index, ipoint+1, 1, iline+1, 1, 0, 0, 0, 0 );
      ipoint += 1; iline += 1;
    }
  }

    // arcs (2D)
  max = mesh_gid_max( MESH_GID_ARC_COORD );
  if ( max>=0 ) fprintf( fp, "Mescape Utilities Variables CreateAlwaysNewPoint 1\n" );
  for ( index=0; index<=max; index++ ) {
    if ( !mesh_gid_dbls( MESH_GID_ARC_COORD, index, dval ) ) continue;
    fprintf( fp, "Mescape Geometry Create Arc\n" );
    for ( i=0; i<3; i++ )
      fprintf( fp, "%s,%s,0.0\n", mesh_gid_g(dval[2*i]).c_str(),
        mesh_gid_g(dval[2*i+1]).c_str() );
    fprintf( fp, "escape\n" );
    mesh_gid_report_object( "ARC", index, ipoint+1, 3, iline+1, 1, 0, 0, 0, 0 );
    ipoint += 3; iline += 1;
  }

    // rectangles: x_0 x_1 y_0 y_1
  max = mesh_gid_max( MESH_GID_RECTANGLE_COORD );
  if ( max>=0 ) fprintf( fp, "Mescape Utilities Variables CreateAlwaysNewPoint 1\n" );
  for ( index=0; index<=max; index++ ) {
    if ( !mesh_gid_dbls( MESH_GID_RECTANGLE_COORD, index, dval ) ) continue;
    fprintf( fp, "Mescape Geometry Create Object Rectangle \n%s %s\n%s %s\nescape\n",
      mesh_gid_g(dval[0]).c_str(), mesh_gid_g(dval[2]).c_str(),
      mesh_gid_g(dval[1]).c_str(), mesh_gid_g(dval[3]).c_str() );
    if ( mesh_gid_switch( MESH_GID_RECTANGLE_HOLLOW, index ) ) {
      fprintf( fp, "Mescape Geometry Delete Surface\n%ld\nescape\n\n", isurface+1 );
      mesh_gid_report_object( "RECTANGLE", index, ipoint+1, 4, iline+1, 4, 0, 0, 0, 0 );
    }
    else {
      isurface++;
      if ( mesh_gid_ints( MESH_GID_RECTANGLE_ELEMENT_GROUP, index, group ) )
        fprintf( fp, "Mescape Data Mat Assign GROUP_%ld Surfaces\n%ld \nescape\n",
          group[0], isurface );
      mesh_gid_report_object( "RECTANGLE", index, ipoint+1, 4, iline+1, 4,
        isurface, 1, 0, 0 );
    }
    ipoint += 4; iline += 4;
  }

    // cylinders (3D)
  max = mesh_gid_max( MESH_GID_CYLINDER_COORD );
  if ( max>=0 ) fprintf( fp, "Mescape Utilities Variables CreateAlwaysNewPoint 1\n" );
  for ( index=0; index<=max; index++ ) {
    if ( !mesh_gid_dbls( MESH_GID_CYLINDER_COORD, index, dval ) ) continue;
    mesh_gid_dbls( MESH_GID_CYLINDER_NORMAL, index, &dval[3] );
    mesh_gid_dbls( MESH_GID_CYLINDER_RADIUS, index, &dval[6] );
    mesh_gid_dbls( MESH_GID_CYLINDER_HEIGHT, index, &dval[7] );
    fprintf( fp, "Mescape Geometry Create Object Cylinder" );
    for ( i=0; i<6; i++ ) fprintf( fp, " %s", mesh_gid_g(dval[i]).c_str() );
    fprintf( fp, " \n%s\n%s\nescape\n", mesh_gid_g(dval[6]).c_str(),
      mesh_gid_g(dval[7]).c_str() );
    n = 0;
    if ( mesh_gid_switch( MESH_GID_CYLINDER_HOLLOW, index ) )
      fprintf( fp, "Mescape Geometry Delete Volume\n%ld\nescape\n\n", ivolume+1 );
    else {
      ivolume++; n = 1;
      if ( mesh_gid_ints( MESH_GID_CYLINDER_ELEMENT_GROUP, index, group ) )
        fprintf( fp, "Mescape Data Mat Assign GROUP_%ld Volumes\n%ld \nescape\n",
          group[0], ivolume );
    }
    mesh_gid_report_object( "CYLINDER", index, ipoint+1, 4, iline+1, 6,
      isurface+1, 4, ivolume, n );
    ipoint += 4; iline += 6; isurface += 4;
  }

    // spheres (3D)
  max = mesh_gid_max( MESH_GID_SPHERE_COORD );
  if ( max>=0 ) fprintf( fp, "Mescape Utilities Variables CreateAlwaysNewPoint 1\n" );
  for ( index=0; index<=max; index++ ) {
    if ( !mesh_gid_dbls( MESH_GID_SPHERE_COORD, index, dval ) ) continue;
    mesh_gid_dbls( MESH_GID_SPHERE_RADIUS, index, &dval[3] );
    fprintf( fp, "Mescape Geometry Create Object Sphere %s %s %s \n%s\nescape\n",
      mesh_gid_g(dval[0]).c_str(), mesh_gid_g(dval[1]).c_str(),
      mesh_gid_g(dval[2]).c_str(), mesh_gid_g(dval[3]).c_str() );
    n = 0;
    if ( mesh_gid_switch( MESH_GID_SPHERE_HOLLOW, index ) )
      fprintf( fp, "Mescape Geometry Delete Volume\n%ld\nescape\n\n", ivolume+1 );
    else {
      ivolume++; n = 1;
      if ( mesh_gid_ints( MESH_GID_SPHERE_ELEMENT_GROUP, index, group ) )
        fprintf( fp, "Mescape Data Mat Assign GROUP_%ld Volumes\n%ld \nescape\n",
          group[0], ivolume );
    }
    mesh_gid_report_object( "SPHERE", index, ipoint+1, 2, iline+1, 4,
      isurface+1, 4, ivolume, n );
    ipoint += 2; iline += 4; isurface += 4;
  }

    // merge coincident points of all objects
  fprintf( fp, "Mescape Utilities Variables ImportTolerance 1e-08 escape escape\n" );
  fprintf( fp, "Mescape Utilities Collapse Points\n" );
  for ( i=1; i<=ipoint; i++ ) fprintf( fp, "%ld\n", i );
  fprintf( fp, "escape\n" );

    // surfaces
  max = mesh_gid_max( MESH_GID_SURFACE_LINE );
  if ( max>=0 ) fprintf( fp, "Mescape Utilities Variables CreateAlwaysNewPoint 1\n" );
  for ( index=0; index<=max; index++ ) {
    n = mesh_gid_ints( MESH_GID_SURFACE_LINE, index, ival );
    if ( n==0 ) continue;
    isurface++;
    fprintf( fp, "Mescape Geometry Create NurbsSurface\n" );
    for ( i=0; i<n; i++ ) fprintf( fp, "%ld\n", ival[i] );
    fprintf( fp, "escape\n" );
    if ( mesh_gid_ints( MESH_GID_SURFACE_ELEMENT_GROUP, index, group ) )
      fprintf( fp, "Mescape Data Mat Assign GROUP_%ld Surfaces\n%ld\nescape\n",
        group[0], isurface );
    if ( mesh_gid_ints( MESH_GID_SURFACE_STRUCTURED_NEL, index, nval ) ) {
      fprintf( fp, "Mescape Meshing Structured Surfaces\n%ld\nescape\n", isurface );
      for ( i=0; i<n; i++ ) {
        if ( nval[i]>0 ) fprintf( fp, "%ld\n%ld\nescape\n", nval[i], ival[i] );
      }
      fprintf( fp, "escape\n" );
    }
    if ( mesh_gid_dbls( MESH_GID_SURFACE_STRUCTURED_SIZE, index, size ) ) {
      fprintf( fp, "Mescape Meshing Structured Surfaces Size\n%ld\nescape\n%s\n",
        isurface, mesh_gid_g(size[0]).c_str() );
      for ( i=0; i<n; i++ ) fprintf( fp, "%ld ", ival[i] );
      fprintf( fp, "\n" );
    }
    mesh_gid_surface_element( fp, index, isurface );
    mesh_gid_report_object( "SURFACE", index, 0, 0, 0, 0, isurface, 1, 0, 0 );
  }

    // volumes (3D)
  max = mesh_gid_max( MESH_GID_VOLUME_SURFACE );
  if ( max>=0 ) fprintf( fp, "Mescape Utilities Variables CreateAlwaysNewPoint 1\n" );
  for ( index=0; index<=max; index++ ) {
    n = mesh_gid_ints( MESH_GID_VOLUME_SURFACE, index, ival );
    if ( n==0 ) continue;
    ivolume++;
    fprintf( fp, "Mescape Geometry Create Volume\n" );
    for ( i=0; i<n; i++ ) fprintf( fp, "%ld ", ival[i] );
    fprintf( fp, "\n" );
      // Professional-suspect: "Mat Assign <group> Volume", not
      // "Mat Assign GROUP_<group> Volumes" as for cylinders and spheres
    if ( mesh_gid_ints( MESH_GID_VOLUME_ELEMENT_GROUP, index, group ) )
      fprintf( fp, "Mescape Data Mat Assign %ld Volume\n%ld\nescape\n",
        group[0], ivolume );
    if ( echo ) {
      cout << "generated by MESH_GID_VOLUME index: " << index << "\n";
      mesh_gid_report( "volumes", ivolume, 1 );
    }
  }

    // nodes on points, lines and surfaces to geometry_list index
  for ( ifam=0; ifam<3; ifam++ ) {
    base = 1 + ifam*MESH_GID_CONDITIONS_N;
    max = mesh_gid_max( idat_conditions[ifam] );
    for ( index=base; index<=max; index++ ) {
      n = mesh_gid_ints( idat_conditions[ifam], index, ival );
      fprintf( fp, "Mescape Data Conditions AssignCond nodes_in_%s_%ld\n",
        conditions_name[ifam], index );
      for ( i=0; i<n; i++ ) fprintf( fp, "%ld\n", ival[i] );
      if ( echo ) {
        cout << "assigned by MESH_GID_ASSIGN_CONDITION_" << conditions_type[ifam]
          << " : " << index << "\n";
        cout << "   to geometry_list: " << index << "\n";
        cout << "   nodes in " << conditions_label[ifam] << " numbers: ";
        for ( i=0; i<n; i++ ) cout << ival[i] << " ";
        cout << "\n";
      }
    }
  }

    // mesh and quit; the file ends without a newline
  mesh_gid_dbls( MESH_GID_SIZE, 0, size );
  fprintf( fp, "Mescape Meshing Generate \n%s\n", mesh_gid_g(size[0]).c_str() );
  fprintf( fp, "Mescape Utilities Calculate\n'Zoom Frame\n" );
  fprintf( fp, "Mescape Utilities Variables CreateAlwaysNewPoint 0 escape escape\n" );
  fprintf( fp, "Mescape Quit\nNo" );

  delete[] ival;
  delete[] nval;
}

  // is an executable gid in one of the PATH directories?
static long int mesh_gid_on_path( void )

{
  const char *path = getenv( "PATH" );
  std::string dirs, dir, file;
  size_t start=0, end=0;
#ifdef _WIN32
  const char separator = ';';
  const char *names[2] = { "gid.exe", "gid.bat" };
#else
  const char separator = ':';
  const char *names[2] = { "gid", "gid" };
#endif
  long int i=0;

  if ( path==NULL ) return 0;
  dirs = path;
  while ( start<=dirs.size() ) {
    end = dirs.find( separator, start );
    if ( end==std::string::npos ) end = dirs.size();
    dir = dirs.substr( start, end-start );
    if ( dir.empty() ) dir = ".";
    for ( i=0; i<2; i++ ) {
      file = dir + "/" + names[i];
      if ( access( file.c_str(), X_OK )==0 ) return 1;
    }
    start = end + 1;
  }
  return 0;
}

static long int mesh_gid_copy_file( const char *from, const char *to )

{
  FILE *in=NULL, *out=NULL;
  char buffer[4096];
  size_t n=0;

  in = fopen( from, "rb" );
  if ( in==NULL ) return 0;
  out = fopen( to, "wb" );
  if ( out==NULL ) {
    fclose( in );
    return 0;
  }
  while ( ( n=fread( buffer, 1, sizeof(buffer), in ) )>0 )
    fwrite( buffer, 1, n, out );
  fclose( in );
  fclose( out );
  return 1;
}

  // remove a directory and everything in it (the GiD project mesh_gid.gid)
static void mesh_gid_remove_directory( const std::string &directory )

{
  DIR *dir=NULL;
  struct dirent *entry=NULL;
  struct stat status;
  std::string file;

  dir = opendir( directory.c_str() );
  if ( dir==NULL ) return;
  while ( ( entry=readdir( dir ) )!=NULL ) {
    if ( !strcmp(entry->d_name,".") || !strcmp(entry->d_name,"..") ) continue;
    file = directory + "/" + entry->d_name;
    if ( stat( file.c_str(), &status )==0 && S_ISDIR(status.st_mode) )
      mesh_gid_remove_directory( file );
    else
      remove( file.c_str() );
  }
  closedir( dir );
  rmdir( directory.c_str() );
}

